"""Delete only inventoried, tracked, superseded media inside this repository."""
from pathlib import Path
import hashlib
import json
import subprocess

root = Path(__file__).resolve().parents[1]
out = root / 'docs/content/r11'
plan_path = root / '.audit-tmp/content-r11/cleanup-plan.json'
plan = json.loads(plan_path.read_text(encoding='utf8'))
assert Path(plan['root']).resolve() == root
tracked = set(subprocess.check_output(['git', '-c', 'core.quotepath=false', 'ls-files'], cwd=root, encoding='utf8').splitlines())
deleted = []
for item in plan['files']:
    name = item['path']
    path = (root / name).resolve()
    assert path.is_relative_to(root) and name in tracked
    assert name.startswith(('docs/content/', 'docs/evidence/'))
    assert not name.startswith(('docs/content/r11/', 'docs/store/'))
    assert path.suffix.lower() in {'.png', '.jpg', '.jpeg', '.webp', '.webm', '.mp4'}
    if not path.is_file():
        continue
    # A verification run may have regenerated this output with the current build.
    # It is still the exact inventoried tracked output, never an untracked file.
    deleted.append({**item, 'removedBytes': path.stat().st_size,
                    'removedSHA256': hashlib.sha256(path.read_bytes()).hexdigest()})
    path.unlink()
receipt = {'status': 'EXECUTED', 'count': len(plan['files']),
           'releasedBytes': sum(i['bytes'] for i in plan['files']),
           'releasedMiB': round(sum(i['bytes'] for i in plan['files']) / 2**20, 2),
           'thisPassRemoved': len(deleted), 'files': plan['files'],
           'preserved': ['All Markdown reviews/reports', 'All pre-existing untracked files',
                         'All store screenshots', 'All original artwork and art-audit inputs',
                         'All attained-save fixtures and JSON verification inputs',
                         'docs/evidence/before: original-source comparison input'],
           'note': 'Historical screenshot output directories can be regenerated by their capture scripts. They are not game/test input fixtures.'}
out.mkdir(parents=True, exist_ok=True)
(out / 'cleanup.json').write_text(json.dumps(receipt, ensure_ascii=False, indent=2), encoding='utf8')
assert all(not (root / i['path']).exists() for i in plan['files'])
print(f"EXECUTED {len(deleted)} files removed; total original scope {receipt['count']} files / {receipt['releasedMiB']} MiB")
